def update_config(cfg, data):
    """A new LineConfig with the browser's values clamped to LIMITS. Unknown keys raise ValueError."""
    changes = {}
    for key, value in data.items():
        if key not in LIMITS:
            raise ValueError("unknown setting: {}".format(key))
        low, high = LIMITS[key]
        number = min(high, max(low, float(value)))
        changes[key] = int(round(number)) if isinstance(low, int) else round(number, 2)
    return cfg._replace(**changes)


class Tuner:
    """Settings shared between the web server thread and the camera loop."""

    def __init__(self, cfg, save=save_params):
        self.cfg = cfg
        self.mask = "line"
        self._save = save
        self._lock = threading.Lock()

    def snapshot(self):
        with self._lock:
            return self.cfg, self.mask

    def state(self):
        return {"roi_top": self.cfg.roi_top, "black_v_max": self.cfg.black_v_max, "mask": self.mask}

    def handle(self, path, data):
        """on_post hook for MjpegServer: /set changes settings, /save writes them to my_params.json."""
        with self._lock:
            if path == "/set":
                data = dict(data)
                mask = data.pop("mask", self.mask)
                if mask not in MASKS:
                    raise ValueError("mask must be one of {}".format(MASKS))
                self.cfg = update_config(self.cfg, data)
                self.mask = mask
                return self.state()
            if path == "/save":
                reply = self.state()
                try:
                    self._save(roi_top=self.cfg.roi_top, black_v_max=self.cfg.black_v_max)
                except OSError as exc:  # e.g. the SD card went read-only
                    reply.update(saved=False, message="บันทึกไม่สำเร็จ: {}".format(exc))
                else:
                    reply.update(saved=True, message="บันทึกแล้ว roi_top={} black_v_max={}".format(
                        self.cfg.roi_top, self.cfg.black_v_max))
                return reply
        return None


def render(frame, cfg, mask_name, fps):
    """Camera frame with ROI, centroid and green box drawn on it, and the chosen mask stacked below."""
    result = detect_line(frame, cfg)
    state = VizState(fsm_state="GREEN" if result.green_box else "", line_roi=result.roi_box,
                     cx=result.cx, cy=result.cy, fps=fps)
    out = draw_overlay(frame, state)
    if result.green_box:
        x, y, w, h = result.green_box
        cv2.rectangle(out, (x, y), (x + w, y + h), SIGN_BOX_COLOR, 2)
    mask = result.mask
    if mask_name == "green":
        x0, y0, w, h = result.roi_box
        mask = green_mask(frame[y0:y0 + h, x0:x0 + w], cfg)
    return with_mask(out, mask)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Tune the Module 3 line mask from a browser.")
    parser.add_argument("--port", type=int, default=8080)
    args = parser.parse_args(argv)

    from jetbot_nstru.hardware import CsiCamera  # imported here so the tests run without a camera

    saved = load_params()
    tuner = Tuner(update_config(LineConfig(), {k: saved[k] for k in LIMITS if k in saved}))
    try:
        server = MjpegServer(port=args.port, page=PAGE, on_post=tuner.handle)
    except OSError as exc:
        sys.exit("เปิด port {} ไม่ได้ ({}) ปิด notebook ที่เปิด MjpegServer อยู่ หรือใช้ --port 8081".format(args.port, exc))
    try:
        camera = CsiCamera(width=320, height=240, lock_exposure=True)
    except RuntimeError as exc:
        server.stop()
        sys.exit(str(exc))

    print("เปิด http://10.42.0.1:{} ใน Chrome  (กด Ctrl+C เพื่อหยุด)".format(server.port))
    print("ค่าเริ่มต้นจาก {}: {}".format(PARAMS_PATH, tuner.state()))
    fps, last = None, time.monotonic()
    with server, camera:
        try:
            while True:
                frame = camera.read()
                now = time.monotonic()
                instant = 1.0 / max(now - last, 1e-3)
                fps = instant if fps is None else 0.9 * fps + 0.1 * instant  # smoothed so the HUD is readable
                last = now
                cfg, mask_name = tuner.snapshot()
                server.push(render(frame, cfg, mask_name, fps))
        except KeyboardInterrupt:
            print("\nหยุดแล้ว ค่าที่บันทึกล่าสุดอยู่ใน {}".format(PARAMS_PATH))


if __name__ == "__main__":
    main()
