def update_settings(settings, data):
    """New settings with the browser's values clamped to LIMITS; min_speed never exceeds max_speed."""
    merged = dict(settings)
    for key, value in data.items():
        if key not in LIMITS:
            raise ValueError("unknown setting: {}".format(key))
        low, high = LIMITS[key]
        merged[key] = round(min(high, max(low, float(value))), 3)
    merged["min_speed"] = min(merged["min_speed"], merged["max_speed"])
    return merged


class Driver:
    """Settings and the run/stop switch, shared between the web server thread and the drive loop."""

    def __init__(self, settings, save=save_params, clock=time.monotonic):
        self.settings = settings
        self.running = False
        self.message = ""
        self._save = save
        self._clock = clock
        self._last_ping = clock()
        self._lost_since = None
        self._lock = threading.Lock()

    def state(self):
        return dict(self.settings, running=self.running, message=self.message)

    def handle(self, path, data):
        """on_post hook for MjpegServer. Every request also counts as a heartbeat."""
        with self._lock:
            self._last_ping = self._clock()
            if path == "/set":
                self.settings = update_settings(self.settings, data)
            elif path == "/start":
                self.running, self.message, self._lost_since = True, "", None
            elif path == "/stop":
                self._halt("หยุดแล้ว")
            elif path == "/save":
                return self._save_settings()
            elif path != "/ping":
                return None
            return self.state()

    def tick(self, now, line_found):
        """Called once per frame. Returns (settings, should_drive) after the safety checks."""
        with self._lock:
            if self.running and now - self._last_ping > HEARTBEAT_TIMEOUT:
                self._halt("หยุดเพราะหน้าเว็บขาดการเชื่อมต่อ")
            if line_found:
                self._lost_since = None
            elif self.running:
                self._lost_since = now if self._lost_since is None else self._lost_since
                if now - self._lost_since > LOST_LINE_STOP:
                    self._halt("หยุดเพราะไม่เห็นเส้นนานเกิน {:.0f} วินาที".format(LOST_LINE_STOP))
            return dict(self.settings), self.running

    def _halt(self, message):
        self.running = False
        self.message = message

    def _save_settings(self):
        reply = self.state()
        try:
            self._save(**self.settings)
        except OSError as exc:  # e.g. the SD card went read-only
            reply.update(saved=False, message="บันทึกไม่สำเร็จ: {}".format(exc))
        else:
            reply.update(saved=True, message="บันทึกแล้ว " + "  ".join(
                "{}={}".format(k, self.settings[k]) for k in sorted(LIMITS)))
        return reply


def steer_and_speed(result, pid, settings, steer, dt):
    """Same control as the notebook: PID on the line error, slow down in curves, keep the last steer when lost."""
    if not result.found:
        return steer, settings["min_speed"]
    steer = pid.update(result.error, dt)
    return steer, speed_for_error(result.error, settings["max_speed"], settings["min_speed"])


def _exit_on_signal(signum, frame):
    raise SystemExit(0)  # unwinds through main's finally, so robot.stop() runs


def main(argv=None):
    # Closing the Jupyter Terminal tab sends SIGHUP; without this the motors keep their last command.
    for sig in (signal.SIGTERM, signal.SIGHUP):
        signal.signal(sig, _exit_on_signal)
    parser = argparse.ArgumentParser(description="Drive the line and tune PID from a browser.")
    parser.add_argument("--port", type=int, default=8080)
    args = parser.parse_args(argv)

    from jetbot_nstru.hardware import CsiCamera, open_robot  # imported here so the tests run without a robot

    saved = load_params()
    driver = Driver(update_settings(DEFAULTS, {k: saved[k] for k in LIMITS if k in saved}))
    trim = MotorTrim(saved.get("left_gain", 1.0), saved.get("right_gain", 1.0))
    line_cfg = LineConfig(roi_top=saved.get("roi_top", 0.55), black_v_max=saved.get("black_v_max", 90))
    try:
        server = MjpegServer(port=args.port, page=PAGE, on_post=driver.handle)
    except OSError as exc:
        sys.exit("เปิด port {} ไม่ได้ ({}) ปิด kernel ของ notebook ทุกตัว หรือใช้ --port 8081".format(args.port, exc))
    try:
        camera = CsiCamera(width=320, height=240, lock_exposure=True)
    except RuntimeError as exc:
        server.stop()
        sys.exit(str(exc))
    robot = open_robot()

    print("เปิด http://10.42.0.1:{} ใน Chrome  (กด Ctrl+C เพื่อจบโปรแกรม)".format(server.port))
    print("ค่าเริ่มต้น: {}  trim={}  roi_top={} black_v_max={}".format(
        driver.settings, tuple(trim), line_cfg.roi_top, line_cfg.black_v_max))
    pid = PID(kp=driver.settings["kp"], kd=driver.settings["kd"])
    steer, moving, fps = 0.0, False, None
    last = time.monotonic()
    with server, camera:
        try:
            while True:
                frame = camera.read()
                now = time.monotonic()
                dt = max(now - last, 1e-3)
                last = now
                fps = 1.0 / dt if fps is None else 0.9 * fps + 0.1 / dt  # smoothed so the HUD is readable

                result = detect_line(frame, line_cfg)
                settings, drive = driver.tick(now, result.found)
                pid.kp, pid.kd = settings["kp"], settings["kd"]
                left = right = 0.0
                if drive:
                    if not moving:
                        pid.reset()
                        steer = 0.0
                    steer, speed = steer_and_speed(result, pid, settings, steer, dt)
                    left, right = mix_motors(speed, steer, trim)
                    robot.set_motors(left, right)
                elif moving:
                    robot.stop()
                moving = drive

                state = VizState(fsm_state="RUN" if drive else "STOP", line_roi=result.roi_box, cx=result.cx,
                                 cy=result.cy, steer=steer, motor_left=left, motor_right=right, fps=fps)
                server.push(with_mask(draw_overlay(frame, state), result.mask))
        except KeyboardInterrupt:
            print("\nจบโปรแกรม ค่าที่บันทึกล่าสุดอยู่ใน {}".format(PARAMS_PATH))
        except RuntimeError as exc:  # camera gives no frame while another process holds it
            sys.exit("{}\nกล้องอาจถูก notebook อื่นใช้อยู่: ใน Jupyter Lab เลือก Kernel > Shut Down All Kernels "
                     "แล้วสั่ง sudo systemctl restart nvargus-daemon ก่อนรันใหม่".format(exc))
        finally:
            robot.stop()


if __name__ == "__main__":
    main()
